// Minimal RFC-4180 CSV parser: quoted fields, doubled quotes, embedded commas
// and newlines, CRLF line endings, optional UTF-8 BOM. No dependencies.

export function parseCsv(text) {
  if (text.charCodeAt(0) === 0xfeff) text = text.slice(1);
  const rows = [];
  let row = [];
  let field = '';
  let inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; } else inQuotes = false;
      } else field += c;
    } else if (c === '"') {
      inQuotes = true;
    } else if (c === ',') {
      row.push(field); field = '';
    } else if (c === '\n') {
      row.push(field); rows.push(row); row = []; field = '';
    } else if (c !== '\r') {
      field += c;
    }
  }
  if (field !== '' || row.length) { row.push(field); rows.push(row); }
  return rows;
}

/** Parse CSV text into objects keyed by the header row. */
export function parseCsvObjects(text) {
  const rows = parseCsv(text);
  const header = rows[0].map((h) => h.trim());
  const out = [];
  for (let i = 1; i < rows.length; i++) {
    const r = rows[i];
    if (r.length === 1 && r[0] === '') continue; // blank line
    const o = {};
    for (let j = 0; j < header.length; j++) o[header[j]] = r[j] ?? '';
    out.push(o);
  }
  return out;
}
